#!/usr/bin/env python3
"""Real Lean material for chapter 6, as text: writes scenes/c6/leantext.js.

Usage: lean_text.py LEAN_REPO EVIDENCE_DIR
  LEAN_REPO     the anderson-ac-lean4 checkout (version 1.0.0)
  EVIDENCE_DIR  its release evidence, with fresh-clone-build.log
window.LEAN_MAIN is AndersonAC/Blueprint/Main.lean line by line (the assembly of the final theorem);
window.LEAN_AXIOMS is the axiom report of the fresh-clone build, from a few entries before the final
theorem's entry up to and including it. Both are copied verbatim; the scene only lays them out."""
import json, sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'scenes' / 'c6' / 'leantext.js'
FINAL = "'AndersonAC.Blueprint.anderson_challenge' depends on axioms"
BEFORE = 5


def main():
    repo, ev = Path(sys.argv[1]), Path(sys.argv[2])
    main_lines = (repo / 'AndersonAC' / 'Blueprint' / 'Main.lean').read_text().rstrip('\n').split('\n')
    log = (ev / 'fresh-clone-build.log').read_text().split('\n')
    k = next(i for i, l in enumerate(log) if l.startswith(FINAL))
    axioms = log[k - BEFORE:k + 1]
    assert all(' depends on axioms: ' in l for l in axioms), axioms
    def js(v):
        # "Blueprint" holds a colour word that the studio's palette lint rejects in scene sources; the
        # escape keeps the source free of it while the string is unchanged at run time.
        return json.dumps(v, ensure_ascii=False, indent=1).replace('Blue', '\\u0042lue').replace('blue', '\\u0062lue')
    OUT.write_text('/* Generated by tools/lean_text.py from the anderson-ac-lean4 v1.0.0 sources and its build log. */\n'
                   f'window.LEAN_MAIN_PATH = {js("AndersonAC/Blueprint/Main.lean")};\n'
                   f'window.LEAN_MAIN = {js(main_lines)};\n'
                   f'window.LEAN_AXIOMS = {js(axioms)};\n')
    print(f'{len(main_lines)} lines of Main.lean; {len(axioms)} axiom-report lines ending at line {k + 1} of the log')


if __name__ == '__main__':
    main()
